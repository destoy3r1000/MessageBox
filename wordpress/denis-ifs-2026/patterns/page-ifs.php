<h1 class="wp-block-heading">What’s IFS?</h1>
<!-- /wp:heading -->

<!-- wp:paragraph {"align":"center"} -->
<p>Internal Family Systems is an experiential therapy. It uses our senses as a gateway to the subconscious.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"align":"full","style":{"spacing":{"padding":{"bottom":"72px"}}},"layout":{"type":"constrained"}} -->
<div class="wp-block-group alignfull" style="padding-bottom:72px"><!-- wp:columns -->
<div class="wp-block-columns"><!-- wp:column -->
<div class="wp-block-column"><!-- wp:paragraph {"fontSize":"large","fontFamily":"serif"} -->
<p class="has-serif-font-family has-large-font-size">Our brain processes much more than our conscious mind can access. Our body records our experiences and gives us sensory cues when we face something similar.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:column -->

<!-- wp:column -->
<div class="wp-block-column"><!-- wp:paragraph -->
<p>Something just feels “right” or “scary,” and we move towards or avoid it. It’s that <strong>gut feeling</strong>, a soup of everything we’ve experienced before.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>These cues are often not interconnected, which might feel quite confusing. We might want to both rest and keep working at the same time. And we might bash ourselves with criticism if we decide to lie down when the job isn’t done.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>In IFS, we call these cues, sensations, and thoughts <em>parts</em>. That way, we can structure them and find and heal the underlying causes.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:column --></div>
<!-- /wp:columns --></div>
