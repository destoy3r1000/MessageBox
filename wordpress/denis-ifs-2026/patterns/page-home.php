<h2 class="wp-block-heading">What’s IFS?</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"dr-lead"} -->
<p class="dr-lead">IFS is an experiential therapy. It uses our senses as a gateway to the subconscious.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Our brain processes much more than our conscious mind can access. Our body records our experiences and gives us <strong>sensory cues</strong> when we face something similar. Something just feels “right” or “scary,” and we move towards or avoid it. It’s that <strong>gut feeling</strong>, a soup of everything we’ve experienced before.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>These cues are often not interconnected, which might feel quite confusing. We might want to both rest and keep working at the same time. And we might bash ourselves with criticism if we decide to lie down when the job isn’t done.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>In IFS, we call these cues, sensations, and thoughts <em>parts</em>. That way, we can structure them and find and heal the underlying causes.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>There is a lot more to say about it. You can find a more detailed explanation by clicking the button below, or I’ll be happy to explain more during our (free) intake session.</p>
