<details class="wp-block-details" open><summary>Do I need to know what I want to work on?</summary><!-- wp:paragraph {"className":"is-style-script"} -->
<p class="is-style-script">not at all</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We can start with whatever is bothering you at the moment, even if you find it difficult to put into words. As we explore, we may notice feelings or connections you hadn’t been aware of.</p>
