<details class="wp-block-details"><summary>Do I need to know anything about IFS?</summary><!-- wp:paragraph {"className":"is-style-script"} -->
<p class="is-style-script">no prior knowledge is needed</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>I enjoy introducing people to IFS and will explain how it works during our introductory consultation.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>You don’t need to learn any terminology or prepare beforehand. I’ll guide you as we go.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do you only work with queer people and expats?</summary><!-- wp:paragraph {"className":"is-style-script"} -->
<p class="is-style-script">no</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Queer people and expats are the main focus of my practice, but you don’t need to belong to either group to work with me.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>And if you do, our sessions don’t have to focus on your identity or life abroad. We can explore whatever brings you here.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What happens in the first session?</summary><!-- wp:paragraph {"className":"is-style-script"} -->
<p class="is-style-script">a free, 30-minute introductory consultation</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We’ll get to know each other a little, talk about what brings you here, and leave room for your questions. I’ll explain how I work and, if there’s time and you’d like to, we can try a brief IFS exercise to give you a feel for the approach.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>There’s no obligation to book further sessions.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How often would we meet, and for how long?</summary><!-- wp:paragraph -->
<p>We’ll discuss a rhythm that suits your needs and availability during our introductory consultation.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>There’s no fixed number of sessions: how long we work together depends on what you want to explore and how the work develops.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The first few sessions give us a chance to see how the approach feels for you, and we’ll keep checking in about whether it’s helping.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>How do online sessions work?</summary><!-- wp:paragraph -->
<p>You can choose an available appointment through my <a href="https://cal.com/denisruksha?orgRedirection=true">online booking calendar</a> and join our session from your laptop or phone.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Find a private space where you feel comfortable and can speak without being overheard or interrupted. A reliable internet connection and clear audio are important; headphones with a microphone can help.</p>
